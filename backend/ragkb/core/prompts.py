# Многозапросное расширение: одна формулировка вопроса часто лексически
# не пересекается с документом. Несколько перефразировок повышают recall.
# Ответ просим в JSON: разбор по строкам ломается о нумерацию и вводные
# слова, а запасной разбор всё равно остаётся в parse_expanded_queries.
QUERY_EXPANSION_PROMPT = """Переформулируй вопрос пользователя {n} разными способами для поиска по базе документов.
Используй синонимы и официальную/канцелярскую лексику, которая может встречаться в регламентах.
Ответь строго в формате JSON: {{"queries": ["переформулировка 1", "переформулировка 2"]}}
Без пояснений, без markdown и без нумерации.

Вопрос: {question}"""


def format_context(hits, max_chars: int = 12000) -> str:
    """Собирает пронумерованный контекст, не превышая бюджет символов.

    Номера здесь — те же `[N]`, на которые обязана ссылаться модель:
    `RagChain.cited_sources` разбирает их обратно в источники ответа.
    """
    parts: list[str] = []
    total = 0
    for i, hit in enumerate(hits, start=1):
        header = f"[{i}] Источник: {hit.citation}"
        body = hit.text.strip()
        block = f"{header}\n{body}"
        if total + len(block) > max_chars and parts:
            break
        parts.append(block)
        total += len(block)
    return "\n\n".join(parts)

def format_candidates(candidates) -> str:
    """Перечень оригиналов для модели: имя, идентификатор и доступность.

    Закрытые документы тоже попадают в список — с пометкой: модель должна
    видеть, что оригинал недоступен, а не выдумывать ссылку на него.
    """
    if not candidates:
        return (
            "Оригиналов, доступных для скачивания, нет: "
            "отвечай по фрагментам и не обещай файл."
        )
    lines = []
    for candidate in candidates:
        state = (
            "оригинал доступен"
            if candidate["download_allowed"]
            else "оригинал недоступен"
        )
        lines.append(
            f"- {candidate['filename']} (document_id={candidate['document_id']}): {state}"
        )
    return "\n".join(lines)
