# Уплотнение истории диалога в самостоятельный вопрос: без этого «а сколько дней?»
# после «расскажи про отпуск» уходит в поиск как бессмысленный запрос.
CONDENSE_PROMPT = """Ниже история диалога и новый вопрос пользователя.
Переформулируй новый вопрос так, чтобы он был понятен без истории — самостоятельным и полным.
Выведи только переформулированный вопрос, без пояснений.

История:
{history}

Новый вопрос: {question}"""


def format_context(hits, max_chars: int = 12000) -> str:
    """Собирает пронумерованный контекст, не превышая бюджет символов."""
    parts: list[str] = []
    total = 0
    for i, hit in enumerate(hits, start=1):
        header = f"[{i}] Источник: {hit.chunk.citation()}"
        body = hit.chunk.text.strip()
        block = f"{header}\n{body}"
        if total + len(block) > max_chars and parts:
            break
        parts.append(block)
        total += len(block)
    return "\n\n".join(parts)
