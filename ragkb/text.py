"""Нормализация текста и лёгкий стеммер для русского языка.

Русский язык сильно флективен: «отпуска», «отпуску», «отпуском» — одно слово
для человека и три разных токена для BM25. Полноценный морфоанализатор
(pymorphy3) точнее, но тянет словари; здесь — усечение окончаний по правилам,
которое закрывает большую часть случаев и не требует зависимостей.
"""
from __future__ import annotations

import re
from functools import lru_cache

_TOKEN_RE = re.compile(r"[a-zA-Zа-яёА-ЯЁ0-9]+(?:[-_][a-zA-Zа-яёА-ЯЁ0-9]+)*")

# Стоп-слова: служебные части речи, которые не несут смысла для поиска.
